CREATE TABLE documents (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  title VARCHAR(255) NOT NULL,
  description TEXT NULL,
  original_name VARCHAR(255) NOT NULL,
  extension VARCHAR(10) NOT NULL,
  mime_type VARCHAR(100) NOT NULL,
  size_kb INT UNSIGNED NOT NULL,
  storage_path VARCHAR(500) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
  category_id BIGINT UNSIGNED NOT NULL,
  prodi_id BIGINT UNSIGNED NULL,
  uploader_id BIGINT UNSIGNED NOT NULL,
  owner_id BIGINT UNSIGNED NOT NULL,
  owner_role VARCHAR(30) NOT NULL,
  visibility ENUM('private','public') NOT NULL DEFAULT 'private',
  verification_status ENUM('pending','approved','rejected') NULL,
  archived_at DATETIME(3) NULL,
  retention_status ENUM('expired') NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  deleted_at DATETIME(3) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_documents_storage_path (storage_path),
  KEY idx_documents_category (category_id),
  KEY idx_documents_prodi (prodi_id),
  KEY idx_documents_uploader (uploader_id),
  KEY idx_documents_owner (owner_id),
  KEY idx_documents_owner_role_prodi (owner_role, prodi_id),
  KEY idx_documents_public (visibility, verification_status, created_at),
  KEY idx_documents_archived_at (archived_at),
  KEY idx_documents_deleted_at (deleted_at),
  KEY idx_documents_created_at (created_at),
  KEY idx_documents_extension (extension),
  CONSTRAINT fk_documents_category FOREIGN KEY (category_id) REFERENCES categories (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT fk_documents_prodi FOREIGN KEY (prodi_id) REFERENCES prodi (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT fk_documents_uploader FOREIGN KEY (uploader_id) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT fk_documents_owner FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT chk_documents_visibility CHECK (
    (visibility = 'private' AND (verification_status IS NULL OR verification_status = 'rejected'))
    OR
    (visibility = 'public' AND verification_status IS NOT NULL AND verification_status IN ('pending','approved'))
  ),
  CONSTRAINT chk_documents_size CHECK (size_kb BETWEEN 1 AND 10240),
  CONSTRAINT chk_documents_extension CHECK (extension IN ('pdf','docx','xlsx','pptx','zip','png','jpg')),
  CONSTRAINT chk_documents_owner_role CHECK (owner_role IN ('super_admin','dekan','baak','kaprodi','dosen','mahasiswa'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
